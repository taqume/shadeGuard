function detectLanguage(storage, browserLanguages) {
  try {
    const stored = storage?.getItem("shadeguard:language");
    if (stored === "tr" || stored === "en") return stored;
  } catch {}
  return browserLanguages.some((language) => language?.toLowerCase().startsWith("tr")) ? "tr" : "en";
}

export function createI18n(options = {}) {
  let storage = options.storage;
  if (storage === undefined) {
    try { storage = window.localStorage; } catch {}
  }
  const browserLanguages = options.browserLanguages
    ?? (navigator.languages?.length ? navigator.languages : [navigator.language]);
  let language = detectLanguage(storage, browserLanguages);

  function lookup(key) {
    return catalogs[language][key] ?? catalogs.en[key];
  }

  function t(key, values = {}) {
    const template = lookup(key) ?? key;
    return template.replace(/\{([a-zA-Z]+)\}/gu, (_match, name) => String(values[name] ?? `{${name}}`));
  }

  function applyDocument(root = document) {
    root.documentElement.lang = language;
    root.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-aria]").forEach((node) => { node.setAttribute("aria-label", t(node.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-prompt]").forEach((node) => { node.dataset.runPrompt = t(node.dataset.i18nPrompt); });
    const toggle = root.querySelector("#language-toggle");
    if (toggle) {
      toggle.textContent = language === "en" ? "TR" : "EN";
      toggle.setAttribute("aria-label", t("language.switch"));
      toggle.title = t("language.switch");
    }
  }

  function switchLanguage() {
    language = language === "en" ? "tr" : "en";
    try { storage?.setItem("shadeguard:language", language); } catch {}
    return language;
  }

  return {
    get language() { return language; },
    lookup,
    t,
    applyDocument,
    switchLanguage,
  };
}
